package com.tufein.switchrecomphelper.core

import com.tufein.switchrecomphelper.core.fs.Nso
import com.tufein.switchrecomphelper.core.fs.NsoHeader
import com.tufein.switchrecomphelper.core.io.RandomAccessSource
import java.security.MessageDigest

/** What we know about one ExeFS file after extraction; filled in while the pipeline reads it. */
class ExeFsFileInfo(val name: String, val size: Long) {
    /** SHA-256 of the file as stored in ExeFS; null if it could not be computed. */
    @Volatile var sha256: String? = null
    var nso: NsoInfo? = null
}

class NsoInfo(val buildId: String, val uncompressedPath: String, val uncompressedSize: Long) {
    @Volatile var uncompressedSha256: String? = null
    /** Per segment: true = hash checked against the NSO header; null until decompressed. */
    @Volatile var segmentHashChecked: List<Boolean>? = null
}

/**
 * Hashes a file while the pipeline reads it front to back (the pipeline reads every file exactly once,
 * in order). A read that skips ahead leaves the hash unknown instead of wrong.
 */
internal class DigestingSource(private val inner: RandomAccessSource, private val onDone: (String) -> Unit) : RandomAccessSource {
    private val md = MessageDigest.getInstance("SHA-256")
    private var next = 0L
    private var broken = false
    override val size: Long get() = inner.size

    init {
        if (inner.size == 0L) onDone(md.digest().toHex())
    }

    override fun read(position: Long, dst: ByteArray, offset: Int, length: Int): Int {
        val n = inner.read(position, dst, offset, length)
        if (n > 0 && !broken && next < size) {
            if (position > next) {
                broken = true
            } else if (position + n > next) {
                val skip = (next - position).toInt()
                md.update(dst, offset + skip, n - skip)
                next = position + n
                if (next == size) onDone(md.digest().toHex())
            }
        }
        return n
    }
}

/**
 * The uncompressed NSO, built on first read and dropped once the last byte has been read, so only one
 * executable is held in memory at a time.
 */
internal class UncompressedNsoSource(
    private val nso: RandomAccessSource,
    private val header: NsoHeader,
    private val what: String,
    private val info: NsoInfo,
) : RandomAccessSource {
    override val size: Long = header.uncompressedFileSize
    private var data: ByteArray? = null

    override fun read(position: Long, dst: ByteArray, offset: Int, length: Int): Int {
        if (position < 0 || position >= size) return -1
        val d = data ?: Nso.decompress(nso, header, what).also {
            info.uncompressedSha256 = it.sha256
            info.segmentHashChecked = it.segmentHashChecked
            data = it.bytes
        }.bytes
        val n = minOf(length.toLong(), size - position).toInt()
        System.arraycopy(d, position.toInt(), dst, offset, n)
        if (position + n == size) data = null
        return n
    }
}

/**
 * Writes `recomp_info.toml`: title id, and per ExeFS file its size, SHA-256 and (for NSOs) the build id
 * and the uncompressed copy. Recomp projects pin the exact game version this way (they check the hash of
 * the user's dump before using it), and Switch tooling keys executables by build id.
 */
object RecompInfo {
    const val FILE_NAME = "recomp_info.toml"
    const val FORMAT_VERSION = 1

    fun toml(programId: Long, sourceName: String, files: List<ExeFsFileInfo>): String = buildString {
        append("# Generated by SwitchRecompHelper. Hashes identify this exact dump; compare them with what a recomp expects.\n")
        append("format_version = ").append(FORMAT_VERSION).append('\n')
        append('\n')
        append("[title]\n")
        append("program_id = ").append(str("%016x".format(programId))).append('\n')
        append("source = ").append(str(sourceName)).append('\n')
        for (f in files) {
            append('\n')
            append("[[exefs]]\n")
            append("file = ").append(str("exefs/${f.name}")).append('\n')
            append("size = ").append(f.size).append('\n')
            append("sha256 = ").append(str(f.sha256 ?: "")).append('\n')
            val nso = f.nso ?: continue
            append("build_id = ").append(str(nso.buildId)).append('\n')
            append("uncompressed_file = ").append(str(nso.uncompressedPath)).append('\n')
            append("uncompressed_size = ").append(nso.uncompressedSize).append('\n')
            append("uncompressed_sha256 = ").append(str(nso.uncompressedSha256 ?: "")).append('\n')
            val checked = nso.segmentHashChecked
            append("segment_hashes_checked = ")
                .append(checked?.joinToString(", ", "[", "]") ?: "[]")
                .append(" # .text, .rodata, .data\n")
        }
    }

    /** TOML basic string. Names come from the dump, so escape everything that could break the syntax. */
    private fun str(s: String): String = buildString {
        append('"')
        for (c in s) {
            when {
                c == '"' -> append("\\\"")
                c == '\\' -> append("\\\\")
                c < ' ' || c == '\u007f' -> append("\\u%04x".format(c.code))
                else -> append(c)
            }
        }
        append('"')
    }
}
